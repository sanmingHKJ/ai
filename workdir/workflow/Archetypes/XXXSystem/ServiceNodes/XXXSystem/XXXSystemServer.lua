-- Query: get_damage_for_attack(attacker_id, attack_type) -> int
-- Description: Calculate the expected damage for an attack type based on attacker's stats and attack multipliers.
function CombatSystemServer:getDamageForAttack(attacker_id, attack_type)
    -- Validate input parameters
        if not userId or not data then
            self.log:error("handleBasicAttack: Missing userId or data")
            return 0
        end

        local attacker_id = data.attacker_id
        local target_id = data.target_id
        local attack_type = data.attack_type

        -- Validate attacker and target exist
        if not attacker_id or not target_id then
            self.log:error("handleBasicAttack: Missing attacker_id or target_id")
            return 0
        end

        if not attack_type then
            self.log:error("handleBasicAttack: Missing attack_type")
            return 0
        end

        -- Check if attacker exists in combat state
        local attacker_combat = self.data.CombatState and self.data.CombatState[attacker_id]
        if not attacker_combat then
            self.log:debug("handleBasicAttack: Attacker not in combat state")
            return 0
        end

        -- Check if attacker can currently attack
        if not attacker_combat.can_attack then
            self.log:debug("handleBasicAttack: Attacker cannot attack at this time")
            return 0
        end

        -- Check if target exists in combat state
        local target_combat = self.data.CombatState and self.data.CombatState[target_id]
        if not target_combat then
            self.log:debug("handleBasicAttack: Target not in combat state")
            return 0
        end

        -- Get attacker and target hero instances for stat lookup
        local attacker = self.data.HeroInstance and self.data.HeroInstance[attacker_id]
        local target = self.data.HeroInstance and self.data.HeroInstance[target_id]

        if not attacker or not target then
            self.log:error("handleBasicAttack: Could not find attacker or target hero instance")
            return 0
        end

        -- Calculate base damage based on attack type
        local base_damage = 0
        if attack_type == "melee" then
            base_damage = attacker.attack_power or 10
        elseif attack_type == "ranged" then
            base_damage = math.floor((attacker.attack_power or 10) * 0.9)
        else
            self.log:error("handleBasicAttack: Unknown attack_type: " .. tostring(attack_type))
            return 0
        end

        -- Get attack multiplier (can vary based on weapon, buffs, etc.)
        local attack_multiplier = 1.0

        -- Calculate defense reduction from target
        local target_defense = target.defense or 0
        local defense_reduction = math.max(0, target_defense * 0.1)

        -- Calculate final damage
        local final_damage = math.floor((base_damage * attack_multiplier) - defense_reduction)
        final_damage = math.max(1, final_damage) -- Ensure minimum 1 damage

        -- Store damage calculation for reference
        if not self.data.DamageCalculation then
            self.data.DamageCalculation = {}
        end

        self.data.DamageCalculation[attacker_id] = {
            base_damage = base_damage,
            attack_multiplier = attack_multiplier,
            defense_reduction = defense_reduction,
            final_damage = final_damage,
            damage_type = attack_type
        }

        self.log:info("handleBasicAttack: Attacker " .. tostring(attacker_id) .. 
                      " dealt " .. tostring(final_damage) .. " damage to target " .. 
                      tostring(target_id) .. " using " .. attack_type .. " attack")

        return final_damage
end


