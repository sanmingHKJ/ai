-- Query: is_in_attack_range(attacker_id, target_id, attack_type) -> bool
-- Description: Check if target is within valid attack range for the specified attack type (melee or ranged).
function CombatSystemServer:isInAttackRange(attacker_id, target_id, attack_type)
    -- Validate input parameters
        if not userId or not data then
            self.log:error("handleBasicAttack: Missing userId or data")
            return 0
        end

        if not data.attacker_id or not data.target_id then
            self.log:error("handleBasicAttack: Missing attacker_id or target_id in data")
            return 0
        end

        -- Get attacker entity
        local attacker = self.data.HeroInstance and self.data.HeroInstance[data.attacker_id]
        if not attacker then
            self.log:error("handleBasicAttack: Attacker not found - " .. tostring(data.attacker_id))
            return 0
        end

        -- Get target entity
        local target = self.data.HeroInstance and self.data.HeroInstance[data.target_id]
        if not target then
            self.log:error("handleBasicAttack: Target not found - " .. tostring(data.target_id))
            return 0
        end

        -- Get combat state for attacker
        local attackerCombatState = self.data.CombatState and self.data.CombatState[data.attacker_id]
        if not attackerCombatState then
            self.log:error("handleBasicAttack: Attacker combat state not found")
            return 0
        end

        -- Check if attacker can attack
        if not attackerCombatState.can_attack then
            self.log:debug("handleBasicAttack: Attacker cannot attack at this time")
            return 0
        end

        -- Check attack range
        local attackRange = 5.0 -- Default melee range
        if data.attack_type == "ranged" then
            attackRange = 15.0
        end

        local distance = (attacker.position - target.position).magnitude
        if distance > attackRange then
            self.log:debug("handleBasicAttack: Target out of range. Distance: " .. tostring(distance) .. ", Range: " .. tostring(attackRange))
            return 0
        end

        -- Calculate damage
        local baseDamage = attacker.attack_power or 10
        local attackMultiplier = 1.0
        local defenseReduction = target.defense or 0

        if data.attack_type == "ranged" then
            attackMultiplier = 0.8
        end

        local calculatedDamage = math.floor(baseDamage * attackMultiplier - (defenseReduction * 0.1))
        calculatedDamage = math.max(1, calculatedDamage) -- Minimum 1 damage

        -- Apply damage to target
        if target.health then
            target.health = target.health - calculatedDamage
            if target.health < 0 then
                target.health = 0
            end
        end

        -- Update combat state
        attackerCombatState.last_attack_time = os.time()
        attackerCombatState.in_combat = true

        -- Log the attack
        self.log:info("handleBasicAttack: Attacker " .. tostring(data.attacker_id) .. " dealt " .. tostring(calculatedDamage) .. " damage to target " .. tostring(data.target_id))

        -- Emit attack event
        local EventID = require(script.Parent.Parent.Parent.Runtime.EventID)
        if EventID then
            self.events:emit(EventID.ACTION_BASIC_ATTACK, {
                attacker_id = data.attacker_id,
                target_id = data.target_id,
                damage_amount = calculatedDamage,
                attack_type = data.attack_type,
                timestamp = os.time()
            })
        end

        return calculatedDamage
end


