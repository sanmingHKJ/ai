--------------------------------------框架事件说明--------------------------------------
--事件说明：
--带Server开头的事件名称为服务端事件

--------------------------------------ActorManager事件--------------------------------------

--事件名: ServerActorCreated
--参数: actor
--说明: 服务端Actor创建事件

--事件名: ServerActorDestroy
--参数: actor
--说明: 服务端Actor销毁事件

--事件名: ActorCreated
--参数: actor
--说明: 客户端Actor创建事件

--事件名: ActorDestroy
--参数: actor
--说明: 客户端Actor销毁事件

--------------------------------------Actor事件--------------------------------------

--<Actor类事件>

--事件名: ServerStateChanged
--参数: oldState,newState
--说明: 服务端状态改变事件

--事件名: StateChanged
--参数: oldState,newState
--说明: 客户端状态改变事件


--<属性类事件>

--事件名: ServerStatChanged
--参数: statName,oldValue,newValue
--说明: 服务端属性改变事件

--事件名: ServerStatsChanged
--参数: 无
--说明: 服务端所有属性改变事件

--事件名: StatChanged
--参数: statName,oldValue,newValue
--说明: 客户端属性改变事件

--<战斗类事件>

--事件名: ServerApplyDamage
--参数: damageData
--说明: 服务端应用伤害事件

--事件名: ServerTakeDamage
--参数: damageResult
--说明: 服务端承受伤害事件

--事件名: TakeDamage
--参数: damageResult
--说明: 客户端承受伤害事件


--<技能类事件>

--事件名: ServerSkillEvent
--参数: skill,event,params
--说明: 服务端技能事件

--事件名: SkillEvent
--参数: skill,event,params
--说明: 客户端技能事件

--事件名: AllSkills
--参数: skills
--说明: 所有技能事件

--事件名: StartCast
--参数: skill
--说明: 开始释放技能事件

--事件名: LeanSkill
--参数: skill
--说明: 学习技能事件

--事件名: ForgetSkill
--参数: skill
--说明: 忘记技能事件



